// Renders src/utils/privacyPolicy.ts to the public page App Store Connect links
// to, so the in-app policy and the hosted one are the same words.
//   node scripts/build-privacy-page.mjs
// Then redeploy netlify-youtube-proxy/ for the change to go live.
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'

const bundle = await build({
  entryPoints: ['src/utils/privacyPolicy.ts'],
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
})
const policy = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`)

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const sections = policy.PRIVACY_SECTIONS.map((section) => [
  `<h2>${escape(section.title)}</h2>`,
  ...(section.paragraphs ?? []).map((paragraph) => `<p>${escape(paragraph)}</p>`),
  section.bullets ? `<ul>${section.bullets.map((bullet) => `<li>${escape(bullet)}</li>`).join('')}</ul>` : '',
].join('\n')).join('\n')

const html = `<!doctype html>
<!-- Generated by scripts/build-privacy-page.mjs from src/utils/privacyPolicy.ts. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>BestTake Privacy Policy</title>
<style>
  :root { color-scheme: light dark; --ink: #0f172a; --body: #334155; --muted: #64748b; --bg: #f8fbff; --link: #0071e3; }
  @media (prefers-color-scheme: dark) { :root { --ink: #f8fafc; --body: #cbd5e1; --muted: #94a3b8; --bg: #0b1220; --link: #4da3ff; } }
  body { margin: 0; background: var(--bg); color: var(--body); font: 16px/1.6 -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; }
  main { max-width: 42rem; margin: 0 auto; padding: 3rem 1rem 4rem; }
  h1 { color: var(--ink); font-size: 2rem; line-height: 1.2; margin: 0 0 1rem; }
  h2 { color: var(--ink); font-size: 1.15rem; margin: 2rem 0 0.5rem; }
  ul { padding-left: 1.2rem; } li + li { margin-top: 0.4rem; }
  a { color: var(--link); } .lead { font-size: 1.1rem; font-weight: 600; } .date { color: var(--muted); font-size: 0.9rem; }
</style>
</head>
<body>
<main>
<h1>BestTake Privacy Policy</h1>
<p class="date">Effective ${escape(policy.PRIVACY_EFFECTIVE_DATE)}</p>
<p class="lead">${escape(policy.PRIVACY_SUMMARY)}</p>
${sections}
<h2>Contact</h2>
<p>Questions about privacy: <a href="mailto:${policy.PRIVACY_CONTACT_EMAIL}">${policy.PRIVACY_CONTACT_EMAIL}</a></p>
<p>For help with the app, visit <a href="/support.html">BestTake Support</a>.</p>
</main>
</body>
</html>
`

writeFileSync('netlify-youtube-proxy/privacy.html', html)
console.log('wrote netlify-youtube-proxy/privacy.html')
